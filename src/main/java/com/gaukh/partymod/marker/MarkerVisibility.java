package com.gaukh.partymod.marker;

/**
 * Enum representing marker visibility options.
 */
public enum MarkerVisibility {
    /**
     * Only the owner can see the marker.
     */
    PRIVATE,

    /**
     * Only party members can see the marker.
     */
    PARTY,

    /**
     * Everyone can see the marker.
     */
    GLOBAL
}
